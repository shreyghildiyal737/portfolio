import type { NextConfig } from "next";

// Security headers applied to every route. HSTS is already set by Vercel.
// (No CSP here yet - a strict, nonce-based CSP needs per-request middleware and
// careful testing against the inline styles/scripts; tracked as a follow-up.)
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), browsing-topics=()",
  },
];

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
